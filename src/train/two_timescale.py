"""E6 (stretch): online two-timescale DPO.

Fast timescale  : a reward model r_hat (linear head on frozen sentence embeddings)
                  fitted to the annotator's *sampled* labels on pairs freshly
                  generated by the current policy, step size a_n = a0 (n+1)^-p_fast.
Slow timescale  : the LoRA policy, trained with a *soft* DPO loss whose label is
                  sigmoid(r_hat(y_w) - r_hat(y_l)), step size b_n = b0 (n+1)^-p_slow,
                  p_slow > p_fast so b_n / a_n -> 0 (Borkar, ch. 6).

The pre-registered secondary analysis fits E||theta_n - theta_T||^2 ~ C a_n + b(eps):
we save the flattened LoRA parameters every ``snapshot_every`` steps so the
curve can be computed afterwards (analysis/fits.py).  The reference policy is the
same model with adapters disabled, so no second copy of the base model is needed.
"""
from __future__ import annotations

import json
import os
import time
from typing import Dict, List

import numpy as np
import pandas as pd
import torch

from ..common.config import run_dir
from ..common.kaggle_env import resolve_dtype, torch_device
from ..common.seed import derive_seed, seed_everything
from ..prefgen.annotate import annotator_rewards, apply_flip_noise, exact_pair_probs, mixture_weights
from ..prefgen.build import cache_paths
from ..prefgen.reward import DEFAULT_AXIS_MODEL, DEFAULT_REWARD_MODEL
from ..prefgen.sample import sample_responses
from .dataset import collate, encode_prompt_response, sequence_logprobs
from .dpo_loss import compute_loss
from .trainer import load_policy


class Embedder:
    def __init__(self, name: str, device):
        from transformers import AutoModel, AutoTokenizer

        self.tok = AutoTokenizer.from_pretrained(name)
        self.model = AutoModel.from_pretrained(name).to(device).eval()
        self.device = device

    @torch.no_grad()
    def __call__(self, texts: List[str]) -> torch.Tensor:
        enc = self.tok(texts, return_tensors="pt", padding=True, truncation=True, max_length=256).to(self.device)
        h = self.model(**enc).last_hidden_state
        m = enc["attention_mask"].unsqueeze(-1).float()
        return ((h * m).sum(1) / m.sum(1)).float()


class Scorer:
    """Exact annotator probabilities for freshly generated pairs (same definition as prefgen.annotate)."""

    def __init__(self, cfg: Dict, device, mu_sd: Dict[str, float]):
        from transformers import AutoModelForSequenceClassification, AutoTokenizer

        a = cfg["annotator"]
        self.cfg = a
        self.mu_sd = mu_sd
        self.device = device
        self.rtok = AutoTokenizer.from_pretrained(a.get("true_reward_model", DEFAULT_REWARD_MODEL))
        self.rm = AutoModelForSequenceClassification.from_pretrained(a.get("true_reward_model", DEFAULT_REWARD_MODEL)).to(device).eval()
        self.need_axis = int(a.get("mixture", {}).get("K", 1)) > 1 and float(a.get("mixture", {}).get("minority_mass", 0)) > 0
        if self.need_axis:
            self.atok = AutoTokenizer.from_pretrained(a.get("axis_model", DEFAULT_AXIS_MODEL))
            self.am = AutoModelForSequenceClassification.from_pretrained(a.get("axis_model", DEFAULT_AXIS_MODEL)).to(device).eval()

    @torch.no_grad()
    def __call__(self, prompts: List[str], responses: List[str], lengths: List[int]):
        enc = self.rtok(prompts, responses, return_tensors="pt", padding=True, truncation=True, max_length=1024).to(self.device)
        r = self.rm(**enc).logits[:, 0].float().cpu().numpy()
        rz = (r - self.mu_sd["mu_r"]) / self.mu_sd["sd_r"]
        if self.need_axis:
            enc2 = self.atok(responses, return_tensors="pt", padding=True, truncation=True, max_length=512).to(self.device)
            lg = self.am(**enc2).logits.float().cpu().numpy()
            f = lg[:, 1] - lg[:, 0]
            fz = (f - self.mu_sd["mu_f"]) / self.mu_sd["sd_f"]
        else:
            fz = np.zeros_like(rz)
        return rz, fz


def train_two_timescale(cfg: Dict) -> Dict:
    t, o = cfg["train"], cfg["online"]
    seed = int(t["seed"])
    seed_everything(derive_seed(seed, "online"))
    device = torch_device()
    dtype = resolve_dtype(cfg["model"].get("dtype", "auto"))
    out_dir = run_dir(cfg)

    with open(cache_paths(cfg)["prompts"]) as f:
        prompts = json.load(f)["train"]
    cache = pd.read_parquet(cache_paths(cfg)["responses"])
    tr = cache[cache["split"] == "train"]
    mu_sd = {"mu_r": float(tr["rstar_raw"].mean()), "sd_r": float(tr["rstar_raw"].std() or 1.0), "mu_f": float(tr["f_raw"].mean()), "sd_f": float(tr["f_raw"].std() or 1.0)}

    cfg["train"]["gradient_checkpointing"] = False  # generation every step; checkpointing would disable the KV cache
    tok, model = load_policy(cfg, device, dtype)
    tok.padding_side = "left"
    scorer = Scorer(cfg, device, mu_sd)
    emb = Embedder(o.get("embedder", "sentence-transformers/all-MiniLM-L6-v2"), device)
    dim = emb(["x"]).shape[-1]
    rhat = torch.nn.Linear(dim, 1).to(device)
    pol_params = [p for p in model.parameters() if p.requires_grad]
    opt_pol = torch.optim.SGD(pol_params, lr=float(o["b0"]))
    opt_rm = torch.optim.SGD(rhat.parameters(), lr=float(o["a0"]))

    rng = np.random.default_rng(derive_seed(seed, "online_prompts"))
    B = int(o.get("prompts_per_step", 4))
    steps = int(o["steps"])
    snap_every = int(o.get("snapshot_every", 25))
    mp, ml = int(t["max_prompt_length"]), int(t["max_length"])
    w = mixture_weights(cfg["annotator"])
    gamma = float(cfg["annotator"].get("gamma", 0.0))
    eta = float(cfg["annotator"].get("label_flip_eta", 0.0))
    hist: List[Dict] = []
    snaps: List[np.ndarray] = []
    snap_steps: List[int] = []
    t0 = time.time()

    def flat_params() -> np.ndarray:
        return torch.cat([p.detach().float().flatten().cpu() for p in pol_params]).numpy()

    for n in range(steps):
        a_n = float(o["a0"]) * (n + 1) ** (-float(o["p_fast"]))
        b_n = float(o["b0"]) * (n + 1) ** (-float(o["p_slow"]))
        for g in opt_rm.param_groups:
            g["lr"] = a_n
        for g in opt_pol.param_groups:
            g["lr"] = b_n

        # 1. sample two responses per prompt from the current policy
        pidx = rng.choice(len(prompts), size=B, replace=False)
        ps = [prompts[i] for i in pidx]
        model.eval()
        model.config.use_cache = True
        samples = sample_responses(model, tok, ps, k=2, temperature=float(o.get("temperature", 0.8)), top_p=0.95, max_new_tokens=int(o.get("max_new_tokens", 128)), batch_size=B, seed=derive_seed(seed, f"gen{n}"))
        model.config.use_cache = False
        model.train()
        resp = [s["response"] or "(empty)" for s in samples]
        lens = [s["n_tokens"] for s in samples]
        prompt_of = [ps[s["prompt_idx"]] for s in samples]

        # 2. exact annotator probabilities and sampled labels
        rz, fz = scorer(prompt_of, resp, lens)
        labels, pw_idx, pl_idx, p_exact = [], [], [], []
        for b in range(B):
            i, j = 2 * b, 2 * b + 1
            R = annotator_rewards(rz[[i, j]], fz[[i, j]], cfg["annotator"])
            p = exact_pair_probs(R, np.array(lens, dtype=float)[[i, j]], gamma, w)[(0, 1)]
            pn = apply_flip_noise(p, eta)
            y = rng.random() < pn
            labels.append(1.0 if y else 0.0)
            pw_idx.append(i if y else j)
            pl_idx.append(j if y else i)
            p_exact.append(p)

        # 3. fast timescale: reward model on the sampled labels
        E = emb([f"{p}\n\n{r}" for p, r in zip(prompt_of, resp)])
        d = rhat(E[0::2]).squeeze(-1) - rhat(E[1::2]).squeeze(-1)
        y_t = torch.tensor(labels, device=device)
        loss_rm = torch.nn.functional.binary_cross_entropy_with_logits(d, y_t)
        opt_rm.zero_grad()
        loss_rm.backward()
        opt_rm.step()

        # 4. slow timescale: soft DPO with the learned reward's label
        with torch.no_grad():
            rh = rhat(E).squeeze(-1)
            p_label = torch.sigmoid(rh[pw_idx] - rh[pl_idx])
        enc_w = [encode_prompt_response(tok, prompt_of[i], resp[i], mp, ml) for i in pw_idx]
        enc_l = [encode_prompt_response(tok, prompt_of[i], resp[i], mp, ml) for i in pl_idx]
        tok.padding_side = "right"
        bw = collate(enc_w, tok.pad_token_id, device)
        bl = collate(enc_l, tok.pad_token_id, device)
        tok.padding_side = "left"
        with torch.no_grad(), model.disable_adapter():
            ref_w = sequence_logprobs(model, bw)
            ref_l = sequence_logprobs(model, bl)
        lp_w = sequence_logprobs(model, bw)
        lp_l = sequence_logprobs(model, bl)
        res = compute_loss("soft", lp_w, lp_l, ref_w, ref_l, float(t["beta"]), p_label=p_label)
        opt_pol.zero_grad()
        res["loss"].backward()
        torch.nn.utils.clip_grad_norm_(pol_params, 1.0)
        opt_pol.step()

        rec = {"step": n + 1, "a_n": a_n, "b_n": b_n, "loss_rm": float(loss_rm.item()), "loss_pol": float(res["loss"].item()), "mean_p_exact": float(np.mean(p_exact)), "rm_label_agreement": float(((p_label > 0.5).float() == 1).float().mean().item()), "elapsed_s": time.time() - t0}
        hist.append(rec)
        if (n + 1) % 5 == 0:
            print(json.dumps(rec))
        if (n + 1) % snap_every == 0 or n + 1 == steps:
            snaps.append(flat_params())
            snap_steps.append(n + 1)

    final = snaps[-1]
    dist = [float(np.sum((s - final) ** 2)) for s in snaps]
    pd.DataFrame({"step": snap_steps, "sq_dist_to_final": dist, "a_n": [float(o["a0"]) * s ** (-float(o["p_fast"])) for s in snap_steps]}).to_csv(os.path.join(out_dir, "convergence_curve.csv"), index=False)
    pd.DataFrame(hist).to_csv(os.path.join(out_dir, "train_history.csv"), index=False)
    adapter_dir = os.path.join(out_dir, "adapter")
    model.save_pretrained(adapter_dir)
    torch.save(rhat.state_dict(), os.path.join(out_dir, "rhat.pt"))
    return {"steps": steps, "adapter": adapter_dir, "final_loss_pol": hist[-1]["loss_pol"], "final_loss_rm": hist[-1]["loss_rm"], "train_gpu_hours": (time.time() - t0) / 3600}
